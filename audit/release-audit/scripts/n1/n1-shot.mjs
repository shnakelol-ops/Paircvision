import { chromium, devices } from "playwright";
import { readFileSync } from "node:fs";
const S = "/tmp/claude-0/-home-user-Paircvision/5b353f9c-46ec-5c23-9500-866989574214/scratchpad";
const store = JSON.parse(readFileSync(`${S}/runs-release/B/state/before-review-ops.json`, "utf8"));
const t = JSON.parse(readFileSync(`${S}/n1-geometry.json`, "utf8")).find((x) => x.half === "1H" && x.time === "14:00");
const b = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium-1243/chrome-linux64/chrome" });
const page = await (await b.newContext({ ...devices["Pixel 7"] })).newPage();
await page.goto("http://localhost:5199/pro-tagger");
await page.evaluate((v) => localStorage.setItem("pitchflow_pro_tagger_matches_v1", JSON.stringify(v)), store);
await page.reload();
await page.getByText("Saved Matches").tap();
await page.getByRole("button", { name: "Review match", exact: true }).first().tap();
await page.getByRole("button", { name: /Event Map/ }).first().tap();
await page.waitForTimeout(900);
await page.getByRole("button", { name: "H1", exact: true }).first().tap();
await page.getByRole("button", { name: "FOR", exact: true }).first().tap();
await page.getByRole("button", { name: "T/O", exact: true }).first().tap();
await page.waitForTimeout(300);
const box = await page.locator("canvas").first().boundingBox();
const m = Math.min(24, Math.max(8, Math.min(box.width, box.height) * 0.03)); const sc = Math.min((box.width - 2 * m) / 160, (box.height - 2 * m) / 100);
await page.touchscreen.tap(box.x + (box.width - 160 * sc) / 2 + t.nx * 160 * sc, box.y + (box.height - 100 * sc) / 2 + t.ny * 100 * sc);
await page.waitForTimeout(400);
await page.screenshot({ path: `${S}/dbg/n1-panel-opened.png` });
await page.locator('[aria-label="Events at this spot"] button').filter({ hasText: "14:00" }).first().tap();
await page.waitForTimeout(300);
await page.screenshot({ path: `${S}/dbg/n1-panel-picked.png` });
await b.close();
